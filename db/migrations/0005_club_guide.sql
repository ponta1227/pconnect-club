## ④ ラバーの交換時期
ラバー（ラケット表面のゴム）は消耗品なので、定期的に交換が必要です。寿命には「酸化」と「摩耗」の2つがあります。

【酸化による寿命】
ラバーは空気に触れていると表面が酸化して、硬く変わっていきます。変わってくると、ボールの引っかかりや弾みが落ちて、プレーに影響が出ます。種類にもよりますが、保護フィルムを付けて保管している場合で、週1回の練習なら半年くらい、週2回以上なら3か月くらいが目安です。手で触ると、新品のときより引っかかりが減って、サラサラしてきます。

【摩耗による寿命】
ボールが当たるたびにラバーの表面には大きな負担がかかり、すり減っていきます。進み方は打つ量や打ち方によって個人差が大きいです。週1回の初心者のうちは酸化のほうが先に来ることもありますが、週2回以上や部活でも練習している方は、摩耗のほうが早く来ます。

ラバーの表面に、クリーナーを使っても消えない斑点がうっすら浮かんできたら、摩耗による寿命のサインです。そろそろ交換しましょう。斑点がはっきり見えるようになったら、なるべく早めに交換してください（できればその前に交換したいところです）。

交換するときは、種類がたくさんあるので、スタッフにご相談ください。クラブで用意することもできますし、ほかで買ったラバーの持ち込みでも貼ります。遠慮なくお声がけください。

